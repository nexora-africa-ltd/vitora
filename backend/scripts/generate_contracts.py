#!/usr/bin/env python3
"""
Generate serializer contract test files by introspecting actual serializer fields.

Usage:
    cd backend
    poetry run python scripts/generate_contracts.py

Discovers all ModelSerializer/Serializer subclasses in hmis/apps/**/serializers.py,
introspects their actual fields, and writes per-app contract test files into
tests/contracts/.
"""
import importlib
import inspect
import os
import sys

import django

# Setup Django
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "hmis.settings.development")
django.setup()

from rest_framework import serializers as drf_serializers  # noqa: E402

# ── Discover all serializer classes ─────────────────────────────────

# Collect serializer modules
APPS_DIR = os.path.join(os.path.dirname(__file__), "..", "hmis", "apps")

def find_serializer_modules(base_dir: str, base_package: str = "hmis.apps") -> list[str]:
    """Walk hmis/apps and find all serializers.py modules."""
    modules = []
    for root, dirs, files in os.walk(base_dir):
        if "serializers.py" in files:
            rel = os.path.relpath(root, base_dir)
            if rel == ".":
                module_path = base_package + ".serializers"
            else:
                module_path = base_package + "." + rel.replace(os.sep, ".") + ".serializers"
            modules.append(module_path)
    return sorted(modules)


def discover_serializers(module_path: str) -> list[tuple[str, type]]:
    """Import a module and return all Serializer subclasses defined in it."""
    try:
        mod = importlib.import_module(module_path)
    except Exception as e:
        print(f"  ⚠ Could not import {module_path}: {e}")
        return []

    results = []
    for name, obj in inspect.getmembers(mod, inspect.isclass):
        # Only classes defined in THIS module (not imported base classes)
        if obj.__module__ != module_path:
            continue
        if not issubclass(obj, drf_serializers.Serializer):
            continue
        # Skip abstract/base serializers
        if name.startswith("Base") or name.startswith("Abstract"):
            continue
        results.append((name, obj))
    return sorted(results, key=lambda x: x[0])


# Group serializers by app label
APP_GROUPS: dict[str, list[tuple[str, str, list[str]]]] = {}

serializer_modules = find_serializer_modules(APPS_DIR)
total_found = 0

for module_path in serializer_modules:
    serializer_classes = discover_serializers(module_path)
    if not serializer_classes:
        continue

    for cls_name, cls in serializer_classes:
        try:
            actual_fields = sorted(cls().fields.keys())
        except Exception as e:
            print(f"  ⚠ Could not instantiate {cls_name}: {e}")
            continue

        # Derive app label
        parts = module_path.split(".")
        apps_idx = parts.index("apps")
        app_parts = parts[apps_idx + 1 : -1]
        app_label = "_".join(app_parts)

        APP_GROUPS.setdefault(app_label, []).append(
            (cls_name, module_path, actual_fields)
        )
        total_found += 1

print(f"Discovered {total_found} serializers across {len(APP_GROUPS)} apps\n")


def generate_test_file(app_label: str, serializers: list) -> str:
    """Generate a contract test file for one app."""
    lines = []
    lines.append('"""')
    lines.append(f"Serializer contract tests for {app_label} app.")
    lines.append("")
    lines.append("Auto-generated by scripts/generate_contracts.py — DO NOT edit field sets manually.")
    lines.append("Re-run the script to update after serializer changes:")
    lines.append("    poetry run python scripts/generate_contracts.py")
    lines.append('"""')
    lines.append("import pytest  # type: ignore")
    lines.append("")

    # Group imports by module
    imports_by_module: dict[str, list[str]] = {}
    for cls_name, module, _ in serializers:
        imports_by_module.setdefault(module, []).append(cls_name)

    for module, cls_names in sorted(imports_by_module.items()):
        cls_list = ", ".join(sorted(cls_names))
        lines.append(f"from {module} import (")
        for cn in sorted(cls_names):
            lines.append(f"    {cn},")
        lines.append(")")
    lines.append("")
    lines.append("")

    # Build CONTRACTS list
    lines.append("CONTRACTS: list[tuple[type, frozenset[str]]] = [")

    for cls_name, _module, fields in serializers:
        lines.append("    (")
        lines.append(f"        {cls_name},")
        lines.append("        frozenset({")
        for f in fields:
            lines.append(f'            "{f}",')
        lines.append("        }),")
        lines.append("    ),")

    lines.append("]")
    lines.append("")
    lines.append("")

    # Helper
    lines.append("def _serializer_id(val):")
    lines.append('    """Return readable test ID for parametrize."""')
    lines.append("    return val.__name__ if isinstance(val, type) else None")
    lines.append("")
    lines.append("")

    # Test class
    lines.append("@pytest.mark.django_db")
    lines.append(f"class TestContracts{app_label.title().replace('_', '')}:")
    lines.append(f'    """Contract tests for {app_label} serializers."""')
    lines.append("")
    lines.append("    @pytest.mark.parametrize(")
    lines.append('        "serializer_class, expected_fields",')
    lines.append("        CONTRACTS,")
    lines.append("        ids=lambda val: _serializer_id(val),")
    lines.append("    )")
    lines.append("    def test_serializer_fields_match_contract(self, serializer_class, expected_fields):")
    lines.append('        """Serializer field set must match the contract exactly."""')
    lines.append("        actual_fields = frozenset(serializer_class().fields.keys())")
    lines.append("")
    lines.append("        added = actual_fields - expected_fields")
    lines.append("        removed = expected_fields - actual_fields")
    lines.append("")
    lines.append("        assert not added, (")
    lines.append('            f"\\n{serializer_class.__name__}: new fields added to serializer.\\n"')
    lines.append('            f"  Added: {sorted(added)}\\n"')
    lines.append('            f"  → Re-run: poetry run python scripts/generate_contracts.py\\n"')
    lines.append('            f"  → Update the frontend Zod schema to include these fields"')
    lines.append("        )")
    lines.append("        assert not removed, (")
    lines.append('            f"\\n{serializer_class.__name__}: fields removed from serializer.\\n"')
    lines.append('            f"  Removed: {sorted(removed)}\\n"')
    lines.append('            f"  → Re-run: poetry run python scripts/generate_contracts.py\\n"')
    lines.append('            f"  → Update the frontend Zod schema to remove these fields"')
    lines.append("        )")
    lines.append("")

    return "\n".join(lines) + "\n"


# Output directory
out_dir = os.path.join(os.path.dirname(__file__), "..", "tests", "contracts")
os.makedirs(out_dir, exist_ok=True)

# Write __init__.py
init_path = os.path.join(out_dir, "__init__.py")
if not os.path.exists(init_path):
    with open(init_path, "w") as f:
        f.write("")

generated = []
for app_label in sorted(APP_GROUPS.keys()):
    serializers = APP_GROUPS[app_label]
    content = generate_test_file(app_label, serializers)
    filename = f"test_{app_label}_contracts.py"
    filepath = os.path.join(out_dir, filename)
    with open(filepath, "w") as f:
        f.write(content)
    generated.append((filename, len(serializers)))
    print(f"  ✓ {filename} ({len(serializers)} serializers)")

print(f"\nGenerated {len(generated)} contract test files in tests/contracts/")
print(f"Total serializers: {sum(c for _, c in generated)}")
print("\nNext steps:")
print("  1. Delete the old tests/contracts/test_contracts.py")
print("  2. Run: poetry run pytest tests/contracts/ --no-cov -q")
