/**
 * Patient Repository Tests
 * 
 * Test suite for patient CRUD operations with offline sync queue integration.
 * Following TDD methodology - these tests are written BEFORE implementation.
 * 
 * Test Coverage:
 * - Create operations (5 tests)
 * - Read operations (7 tests)
 * - Update operations (4 tests)
 * - Delete operations (3 tests)
 * - Offline behavior (1 test)
 * Total: 20 tests
 */

import { Database } from '@nozbe/watermelondb';
import { Patient, SyncQueue } from '../../lib/db/models';
import { initDatabase } from '../../lib/db';
import { patientRepository } from '../../lib/db/repositories/patientRepository';

describe('Patient Repository Tests', () => {
  let database: Database;

  beforeEach(async () => {
    // Initialize fresh database for each test
    database = await initDatabase();
  });

  afterEach(async () => {
    // Clean up database after each test
    if (database) {
      await database.write(async () => {
        await database.unsafeResetDatabase();
      });
    }
  });

  // ==========================================
  // Create Operations (5 tests)
  // ==========================================

  describe('Create Operations', () => {
    test('should create patient with all required fields', async () => {
      const patientData = {
        mrn: 'MRN-20251230-0001',
        firstName: 'John',
        lastName: 'Doe',
        dateOfBirth: '1990-01-15',
        gender: 'M',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
      };

      const patient = await patientRepository.create(patientData);

      expect(patient.id).toBeDefined();
      expect(patient.mrn).toBe('MRN-20251230-0001');
      expect(patient.firstName).toBe('John');
      expect(patient.lastName).toBe('Doe');
      expect(patient.dateOfBirth).toBe('1990-01-15');
      expect(patient.gender).toBe('M');
      expect(patient.countyId).toBe('county_001');
      expect(patient.subCountyId).toBe('subcounty_001');
    });

    test('should set is_synced to false for new patient', async () => {
      const patientData = {
        mrn: 'MRN-20251230-0002',
        firstName: 'Jane',
        lastName: 'Smith',
        dateOfBirth: '1985-05-20',
        gender: 'F',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
      };

      const patient = await patientRepository.create(patientData);

      expect(patient.isSynced).toBe(false);
    });

    test('should add CREATE entry to sync queue', async () => {
      const patientData = {
        mrn: 'MRN-20251230-0003',
        firstName: 'Alice',
        lastName: 'Johnson',
        dateOfBirth: '1995-03-10',
        gender: 'F',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
      };

      const patient = await patientRepository.create(patientData);

      const syncQueueCollection = database.collections.get<SyncQueue>('sync_queue');
      const syncEntries = await syncQueueCollection.query().fetch();

      expect(syncEntries.length).toBe(1);
      expect(syncEntries[0].operation).toBe('CREATE');
      expect(syncEntries[0].modelName).toBe('Patient');
      expect(syncEntries[0].recordId).toBe(patient.id);
      expect(syncEntries[0].status).toBe('PENDING');
    });

    test('should create patient with optional fields', async () => {
      const patientData = {
        mrn: 'MRN-20251230-0004',
        firstName: 'Bob',
        lastName: 'Wilson',
        dateOfBirth: '1988-07-22',
        gender: 'M',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
        phoneNumber: '+254712345678',
        nationalId: '12345678',
        emergencyContactName: 'Jane Wilson',
        emergencyContactPhone: '+254787654321',
      };

      const patient = await patientRepository.create(patientData);

      expect(patient.phoneNumber).toBe('+254712345678');
      expect(patient.nationalId).toBe('12345678');
      expect(patient.emergencyContactName).toBe('Jane Wilson');
      expect(patient.emergencyContactPhone).toBe('+254787654321');
    });

    test('should generate timestamps for new patient', async () => {
      const patientData = {
        mrn: 'MRN-20251230-0005',
        firstName: 'Charlie',
        lastName: 'Brown',
        dateOfBirth: '1992-11-30',
        gender: 'M',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
      };

      const patient = await patientRepository.create(patientData);

      // Timestamps are automatically generated by WatermelonDB
      expect((patient as any)._raw.created_at).toBeGreaterThan(0);
      expect((patient as any)._raw.updated_at).toBeGreaterThan(0);
    });
  });

  // ==========================================
  // Read Operations (7 tests)
  // ==========================================

  describe('Read Operations', () => {
    beforeEach(async () => {
      // Create test patients
      await patientRepository.create({
        mrn: 'MRN-20251230-0101',
        firstName: 'David',
        lastName: 'Lee',
        dateOfBirth: '1987-04-18',
        gender: 'M',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
        phoneNumber: '+254711111111',
      });

      await patientRepository.create({
        mrn: 'MRN-20251230-0102',
        firstName: 'Emma',
        lastName: 'Davis',
        dateOfBirth: '1993-09-25',
        gender: 'F',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
        phoneNumber: '+254722222222',
      });

      await patientRepository.create({
        mrn: 'MRN-20251230-0103',
        firstName: 'Frank',
        lastName: 'Miller',
        dateOfBirth: '1991-06-12',
        gender: 'M',
        countyId: 'county_002',
        subCountyId: 'subcounty_002',
      });
    });

    test('should fetch all patients with default pagination', async () => {
      const patients = await patientRepository.getAll();

      expect(patients.length).toBe(3);
      expect(patients[0]).toBeInstanceOf(Patient);
    });

    test('should fetch patients with custom pagination', async () => {
      // Create more patients
      for (let i = 0; i < 10; i++) {
        await patientRepository.create({
          mrn: `MRN-20251230-02${i.toString().padStart(2, '0')}`,
          firstName: `Patient${i}`,
          lastName: 'Test',
          dateOfBirth: '1990-01-01',
          gender: 'M',
          countyId: 'county_001',
          subCountyId: 'subcounty_001',
        });
      }

      const firstPage = await patientRepository.getAll(5, 0);
      const secondPage = await patientRepository.getAll(5, 5);

      expect(firstPage.length).toBe(5);
      expect(secondPage.length).toBe(5);
      expect(firstPage[0].id).not.toBe(secondPage[0].id);
    });

    test('should search by first name', async () => {
      const results = await patientRepository.search('David');

      expect(results.length).toBe(1);
      expect(results[0].firstName).toBe('David');
    });

    test('should search by last name', async () => {
      const results = await patientRepository.search('Davis');

      expect(results.length).toBe(1);
      expect(results[0].lastName).toBe('Davis');
    });

    test('should search by MRN', async () => {
      const results = await patientRepository.search('MRN-20251230-0102');

      expect(results.length).toBe(1);
      expect(results[0].mrn).toBe('MRN-20251230-0102');
    });

    test('should search by phone number', async () => {
      const results = await patientRepository.search('+254711111111');

      expect(results.length).toBe(1);
      expect(results[0].phoneNumber).toBe('+254711111111');
    });

    test('should get patient by ID', async () => {
      const allPatients = await patientRepository.getAll();
      const firstPatient = allPatients[0];

      const patient = await patientRepository.getById(firstPatient.id);

      expect(patient).not.toBeNull();
      expect(patient?.id).toBe(firstPatient.id);
    });

    test('should return null for non-existent ID', async () => {
      const patient = await patientRepository.getById('non_existent_id');

      expect(patient).toBeNull();
    });

    test('should get patient by MRN', async () => {
      const patient = await patientRepository.getByMrn('MRN-20251230-0101');

      expect(patient).not.toBeNull();
      expect(patient?.mrn).toBe('MRN-20251230-0101');
    });
  });

  // ==========================================
  // Update Operations (4 tests)
  // ==========================================

  describe('Update Operations', () => {
    let testPatient: Patient;

    beforeEach(async () => {
      testPatient = await patientRepository.create({
        mrn: 'MRN-20251230-0301',
        firstName: 'Grace',
        lastName: 'Taylor',
        dateOfBirth: '1989-12-05',
        gender: 'F',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
      });

      // Clear sync queue from create operation
      const syncQueueCollection = database.collections.get<SyncQueue>('sync_queue');
      await database.write(async () => {
        const entries = await syncQueueCollection.query().fetch();
        await Promise.all(entries.map(entry => entry.markAsDeleted()));
      });
    });

    test('should update patient fields', async () => {
      const updatedPatient = await patientRepository.update(testPatient.id, {
        firstName: 'Gracie',
        phoneNumber: '+254733333333',
      });

      expect(updatedPatient.firstName).toBe('Gracie');
      expect(updatedPatient.phoneNumber).toBe('+254733333333');
      expect(updatedPatient.lastName).toBe('Taylor'); // Unchanged
    });

    test('should set is_synced to false on update', async () => {
      // Manually set synced to true
      await database.write(async () => {
        await testPatient.update((p) => {
          p.isSynced = true;
        });
      });

      const updatedPatient = await patientRepository.update(testPatient.id, {
        firstName: 'Updated',
      });

      expect(updatedPatient.isSynced).toBe(false);
    });

    test('should add UPDATE entry to sync queue', async () => {
      await patientRepository.update(testPatient.id, {
        firstName: 'Updated',
      });

      const syncQueueCollection = database.collections.get<SyncQueue>('sync_queue');
      const syncEntries = await syncQueueCollection.query().fetch();

      expect(syncEntries.length).toBe(1);
      expect(syncEntries[0].operation).toBe('UPDATE');
      expect(syncEntries[0].modelName).toBe('Patient');
      expect(syncEntries[0].recordId).toBe(testPatient.id);
      expect(syncEntries[0].status).toBe('PENDING');
    });

    test('should preserve unmodified fields', async () => {
      const updatedPatient = await patientRepository.update(testPatient.id, {
        phoneNumber: '+254744444444',
      });

      expect(updatedPatient.firstName).toBe('Grace');
      expect(updatedPatient.lastName).toBe('Taylor');
      expect(updatedPatient.dateOfBirth).toBe('1989-12-05');
      expect(updatedPatient.gender).toBe('F');
      expect(updatedPatient.phoneNumber).toBe('+254744444444');
    });
  });

  // ==========================================
  // Delete Operations (3 tests)
  // ==========================================

  describe('Delete Operations', () => {
    let testPatient: Patient;

    beforeEach(async () => {
      testPatient = await patientRepository.create({
        mrn: 'MRN-20251230-0401',
        firstName: 'Harry',
        lastName: 'Anderson',
        dateOfBirth: '1986-03-15',
        gender: 'M',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
      });

      // Clear sync queue from create operation
      const syncQueueCollection = database.collections.get<SyncQueue>('sync_queue');
      await database.write(async () => {
        const entries = await syncQueueCollection.query().fetch();
        await Promise.all(entries.map(entry => entry.markAsDeleted()));
      });
    });

    test('should soft-delete patient', async () => {
      await patientRepository.delete(testPatient.id);

      const patient = await database.collections.get<Patient>('patients').find(testPatient.id);
      expect(patient._raw._status).toBe('deleted');
    });

    test('should add DELETE entry to sync queue', async () => {
      await patientRepository.delete(testPatient.id);

      const syncQueueCollection = database.collections.get<SyncQueue>('sync_queue');
      const syncEntries = await syncQueueCollection.query().fetch();

      expect(syncEntries.length).toBe(1);
      expect(syncEntries[0].operation).toBe('DELETE');
      expect(syncEntries[0].modelName).toBe('Patient');
      expect(syncEntries[0].recordId).toBe(testPatient.id);
      expect(syncEntries[0].status).toBe('PENDING');
    });

    test('should exclude deleted patients from queries', async () => {
      await patientRepository.delete(testPatient.id);

      const allPatients = await patientRepository.getAll();
      const deletedPatient = allPatients.find(p => p.id === testPatient.id);

      expect(deletedPatient).toBeUndefined();
    });
  });

  // ==========================================
  // Offline Behavior (1 test)
  // ==========================================

  describe('Offline Behavior', () => {
    test('should get count of unsynced patients', async () => {
      // Create 3 patients (all unsynced by default)
      await patientRepository.create({
        mrn: 'MRN-20251230-0501',
        firstName: 'Ivan',
        lastName: 'Clark',
        dateOfBirth: '1994-08-20',
        gender: 'M',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
      });

      await patientRepository.create({
        mrn: 'MRN-20251230-0502',
        firstName: 'Julia',
        lastName: 'White',
        dateOfBirth: '1990-11-10',
        gender: 'F',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
      });

      const patient3 = await patientRepository.create({
        mrn: 'MRN-20251230-0503',
        firstName: 'Kevin',
        lastName: 'Martinez',
        dateOfBirth: '1988-02-28',
        gender: 'M',
        countyId: 'county_001',
        subCountyId: 'subcounty_001',
      });

      // Verify all 3 are unsynced initially
      let unsyncedCount = await patientRepository.getUnsyncedCount();
      expect(unsyncedCount).toBe(3);

      // Mark one as synced directly (bypassing repository)
      await database.write(async () => {
        const p = await database.collections.get<Patient>('patients').find(patient3.id);
        await p.update((record) => {
          record.isSynced = true;
        });
      });

      // Verify the patient was marked as synced
      const syncedPatient = await database.collections.get<Patient>('patients').find(patient3.id);
      expect(syncedPatient.isSynced).toBe(true);

      // Now count should be 2
      unsyncedCount = await patientRepository.getUnsyncedCount();
      expect(unsyncedCount).toBe(2);
    });
  });
});
