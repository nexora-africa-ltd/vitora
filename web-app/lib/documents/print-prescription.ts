export interface PrintPrescriptionOptions {
  /** The prescription to print */
  prescription: Prescription;
  /** Patient information (can be extracted from prescription or provided) */
  patient?: PatientInfo;
  /** Facility information for header */
  facility?: FacilityInfo;
  /** Clinician information for signature */
  clinician?: ClinicianInfo;
  /** Encounter ID */
  encounterId?: number | string;
  /** Layout format */
  layout?: LayoutType;
  /** Theme name */
  theme?: string;
  /** Backend-provided verification URL (if available) */
  verificationUrl?: string;
}

