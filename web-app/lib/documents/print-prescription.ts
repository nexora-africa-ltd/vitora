/**
 * Calculate patient age from date of birth
 */
function calculateAge(dob: string | undefined): string {
  if (!dob) return '';
  try {
    const birthDate = new Date(dob);
    const today = new Date();
    let age = today.getFullYear() - birthDate.getFullYear();
    const monthDiff = today.getMonth() - birthDate.getMonth();
    if (monthDiff < 0 || (monthDiff === 0 && today.getDate() < birthDate.getDate())) {
      age--;
    }
    return `${age} years`;
  } catch {
    return '';
  }
}

/**
 * Print a prescription document
 *
 * @param options - Prescription data and print options
 * @returns Promise that resolves to the print window, or null if failed
 */
export async function printPrescription(options: PrintPrescriptionOptions): Promise<Window | null> {
  const {
    prescription,
    patient,
    facility,
    clinician,
    encounterId,
    layout = 'a4',
    theme = 'default',
    verificationUrl,
  } = options;

  // Validate required data
  if (!prescription) {
    console.error('printPrescription: prescription is required');
    return null;
  }

  if (!prescription.items || prescription.items.length === 0) {
    console.warn('printPrescription: prescription has no items');
  }

  // Get QR content with verification status
  const qrContent = getPrescriptionQRContent({
    prescription_number: prescription.prescription_number,
    verification_url: verificationUrl || (prescription as Prescription & { verification_url?: string }).verification_url,
    id: prescription.id,
  });

  // Build render context
  const context: RenderContext = {
    // Patient info (from options or prescription)
    patient: patient || {
      full_name: prescription.patient_name || 'Patient',
      mrn: prescription.patient_mrn || '',
      age: '',
      gender: '',
    },

    // Facility info (from options or defaults)
    facility: facility || prescriptionDefaults.facility,

    // Clinician info (from options or prescription)
    clinician: clinician || {
      name: prescription.prescriber_name || prescriptionDefaults.clinician.name,
      registration_number: prescriptionDefaults.clinician.registration_number,
    },

    // Prescription data
    prescription: {
      prescription_number: prescription.prescription_number,
      prescribed_date: prescription.prescribed_date,
      clinical_notes: prescription.clinical_notes || '',
      items: prescription.items,
    },

    // Encounter ID
    encounter_id: encounterId || prescription.encounter || '',

    // System name
    system_name: prescriptionDefaults.system_name,
  };

  // Render the document with QR code
  const bodyHtml = await renderDocumentAsync(
    PRESCRIPTION_TEMPLATE,
    prescriptionSchema,
    context,
    qrContent
  );

  // Build complete HTML with CSS
  const title = `Prescription - ${prescription.prescription_number}`;
  const html = buildPrintDocument(bodyHtml, title, layout, theme, PRESCRIPTION_CSS);

  // Open print window
  return openPrintWindow(html);
}

