/**
 * Print an invoice document
 *
 * @param options - Invoice data and print options
 * @returns Promise that resolves to the print window, or null if failed
 */
export async function printInvoice(options: PrintInvoiceOptions): Promise<Window | null> {
  const {
    invoice,
    patient,
    facility,
    layout = 'a4',
    theme = 'default',
  } = options;

  // Validate required data
  if (!invoice) {
    console.error('printInvoice: invoice is required');
    return null;
  }

  // Get QR content
  const qrContent = getInvoiceQRContent(invoice);

  // Calculate amounts
  const subtotal = parseFloat(invoice.subtotal || invoice.total_amount);
  const discount = parseFloat(invoice.discount_amount || '0');
  const total = parseFloat(invoice.total_amount);
  const amountPaid = parseFloat(invoice.amount_paid || '0');
  const balanceDue = invoice.balance_due 
    ? parseFloat(invoice.balance_due) 
    : (total - amountPaid);

  // Build render context
  const context: RenderContext = {
    // Patient info
    patient: patient || {
      full_name: invoice.patient_name || 'N/A',
      mrn: invoice.patient_mrn || 'N/A',
    },

    // Facility info
    facility: facility || invoiceDefaults.facility,

    // Invoice data
    invoice: {
      invoice_number: invoice.invoice_number,
      invoice_date: formatDate(invoice.invoice_date),
      due_date: formatDate(invoice.due_date),
      status: invoice.status,
      subtotal: formatCurrency(subtotal),
      discount_amount: formatCurrency(discount),
      total_amount: formatCurrency(total),
      amount_paid: formatCurrency(amountPaid),
      balance_due: formatCurrency(balanceDue),
      items: invoice.items || [],
    },

    // System name
    system_name: invoiceDefaults.system_name,
  };

  // Generate line items HTML
  const lineItemsHtml = buildLineItemsHtml(invoice);

  // Render template
  let bodyHtml = await renderDocumentAsync(
    INVOICE_TEMPLATE,
    invoiceSchema,
    context,
    qrContent
  );

  // Replace line items in table
  bodyHtml = bodyHtml.replace(
    /<tbody>[\s\S]*?<\/tbody>/,
    `<tbody>\n${lineItemsHtml}\n</tbody>`
  );

  // Style the status badge dynamically
  const statusStyle = getStatusBadgeStyle(invoice.status);
  bodyHtml = bodyHtml.replace(
    /<div class="status-badge">/,
    `<div class="status-badge" style="${statusStyle}">`
  );

  // Hide discount row if zero
  if (discount === 0) {
    bodyHtml = bodyHtml.replace(/<div class="row discount-row">[\s\S]*?<\/div>/, '');
  }

  // Build complete HTML with CSS
  const title = `Invoice - ${invoice.invoice_number}`;
  const html = buildPrintDocument(bodyHtml, title, layout, theme, INVOICE_CSS);

  // Open print window
  return openPrintWindow(html);
}

