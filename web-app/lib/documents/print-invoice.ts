// =============================================================================
// PRINT INVOICE OPTIONS
// =============================================================================

export interface PrintInvoiceOptions {
  /** The invoice to print */
  invoice: Invoice;
  /** Patient information (optional, uses invoice fields if not provided) */
  patient?: PatientInfo;
  /** Facility information for header */
  facility?: FacilityInfo;
  /** Layout format (default: a4) */
  layout?: LayoutType;
  /** Theme name */
  theme?: string;
}

// =============================================================================
// UTILITY FUNCTIONS
// =============================================================================

/**
 * Format currency for display
 */
function formatCurrency(amount: number | string): string {
  const num = typeof amount === 'string' ? parseFloat(amount) : amount;
  if (isNaN(num)) return 'KES 0.00';
  return `KES ${num.toLocaleString('en-KE', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

/**
 * Build line items HTML from invoice
 */
function buildLineItemsHtml(invoice: Invoice): string {
  const items = invoice.items || [];
  
  if (items.length === 0) {
    return '<tr><td colspan="4" style="text-align: center; color: #666;">No line items</td></tr>';
  }

  return items
    .map((item: InvoiceItem) => `
      <tr>
        <td>${escapeHtml(item.description || item.service_name || 'Service')}</td>
        <td>${item.quantity}</td>
        <td>${formatCurrency(item.unit_price)}</td>
        <td>${formatCurrency(parseFloat(item.unit_price) * item.quantity)}</td>
      </tr>
    `)
    .join('\n');
}

/**
 * Get status badge CSS
 */
function getStatusBadgeStyle(status: string): string {
  const colors = invoiceStatusColors[status] || { bg: '#f3f4f6', color: '#6b7280' };
  return `background: ${colors.bg}; color: ${colors.color};`;
}

