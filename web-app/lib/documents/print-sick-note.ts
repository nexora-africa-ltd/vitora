// =============================================================================
// PRINT FUNCTION
// =============================================================================

export interface PrintSickNoteOptions {
  sickNote: SickNote;
  patient?: PatientInfo;
  facility?: FacilityInfo;
  clinician?: ClinicianInfo;
  /** Digital signature data. When provided, renders signer identity instead of static placeholder. */
  signature?: SignatureInfo;
}

/**
 * Print a sick note / medical certificate document
 */
export function printSickNote(options: PrintSickNoteOptions): Window | null {
  const { sickNote, patient, facility, clinician, signature } = options;

  if (!sickNote) {
    console.error('printSickNote: sickNote is required');
    return null;
  }

  // Simple mustache-like replacement
  let html = SICK_NOTE_TEMPLATE;

  // Facility
  html = html.replace(/\{\{facility_name\}\}/g, escapeHtml(facility?.name || ''));
  html = html.replace(/\{\{facility_address\}\}/g, escapeHtml(facility?.address || ''));
  html = html.replace(/\{\{facility_phone\}\}/g, escapeHtml(facility?.phone || ''));
  html = html.replace(/\{\{facility_license\}\}/g, escapeHtml(facility?.license || ''));

  // Note
  html = html.replace(/\{\{note_number\}\}/g, escapeHtml(sickNote.note_number));
  html = html.replace(/\{\{issued_date\}\}/g, formatDate(sickNote.issued_at || sickNote.created_at));

  // Patient
  html = html.replace(/\{\{patient_name\}\}/g, escapeHtml(patient?.full_name || sickNote.patient_name));
  html = html.replace(/\{\{patient_mrn\}\}/g, escapeHtml(patient?.mrn || sickNote.patient_mrn));

  // Diagnosis
  html = html.replace(/\{\{diagnosis_text\}\}/g, escapeHtml(sickNote.diagnosis_text));
  if (sickNote.diagnosis_code) {
    html = html.replace(/\{\{#diagnosis_code\}\}([\s\S]*?)\{\{\/diagnosis_code\}\}/g, '$1');
    html = html.replace(/\{\{diagnosis_code\}\}/g, escapeHtml(sickNote.diagnosis_code));
  } else {
    html = html.replace(/\{\{#diagnosis_code\}\}[\s\S]*?\{\{\/diagnosis_code\}\}/g, '');
  }

  // Leave
  html = html.replace(/\{\{leave_start\}\}/g, formatDate(sickNote.leave_start_date));
  html = html.replace(/\{\{leave_end\}\}/g, formatDate(sickNote.leave_end_date));
  html = html.replace(/\{\{leave_days\}\}/g, String(sickNote.leave_days));

  // Recommendations
  if (sickNote.recommendations) {
    html = html.replace(/\{\{#recommendations\}\}([\s\S]*?)\{\{\/recommendations\}\}/g, '$1');
    html = html.replace(/\{\{recommendations\}\}/g, escapeHtml(sickNote.recommendations));
  } else {
    html = html.replace(/\{\{#recommendations\}\}[\s\S]*?\{\{\/recommendations\}\}/g, '');
  }

  // Employer
  if (sickNote.employer_name) {
    html = html.replace(/\{\{#employer_name\}\}([\s\S]*?)\{\{\/employer_name\}\}/g, '$1');
    html = html.replace(/\{\{employer_name\}\}/g, escapeHtml(sickNote.employer_name));
    if (sickNote.employer_contact) {
      html = html.replace(/\{\{#employer_contact\}\}([\s\S]*?)\{\{\/employer_contact\}\}/g, '$1');
      html = html.replace(/\{\{employer_contact\}\}/g, escapeHtml(sickNote.employer_contact));
    } else {
      html = html.replace(/\{\{#employer_contact\}\}[\s\S]*?\{\{\/employer_contact\}\}/g, '');
    }
  } else {
    html = html.replace(/\{\{#employer_name\}\}[\s\S]*?\{\{\/employer_name\}\}/g, '');
  }

  // Clinician
  html = html.replace(/\{\{clinician_name\}\}/g, escapeHtml(clinician?.name || sickNote.issued_by_name));
  html = html.replace(/\{\{clinician_registration\}\}/g, escapeHtml(clinician?.registration_number || ''));

  // Digital signature
  html = html.replace(/\{\{signature_column\}\}/g, renderSignatureColumn(signature));

  const fullHtml = buildPrintDocument(
    html,
    `Sick Note - ${sickNote.note_number}`,
    'a4',
    'default',
    SICK_NOTE_CSS
  );

  return openPrintWindow(fullHtml);
}
