function replaceTemplatePlaceholders(
  template: string,
  data: Record<string, unknown>,
  prefix = ''
): string {
  let result = template;

  for (const [key, value] of Object.entries(data)) {
    const fullKey = prefix ? `${prefix}.${key}` : key;

    if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
      result = replaceTemplatePlaceholders(result, value as Record<string, unknown>, fullKey);
    } else {
      const placeholder = new RegExp(`\\{\\{${fullKey}\\}\\}`, 'g');
      result = result.replace(placeholder, String(value ?? ''));
    }
  }

  return result;
}

function getOrderItems(order: LabOrder): LabOrderItem[] {
  return Array.isArray(order.items) ? order.items : [];
}

function getResultForItem(item: LabOrderItem): LabResult | null {
  return (item.result as LabResult | null) || null;
}

function computeReportStatus(order: LabOrder): { label: string; cssClass: string } {
  const items = getOrderItems(order);
  const results = items.map(getResultForItem).filter(Boolean) as LabResult[];

  if (results.length === 0) {
    return {
      label: labReportStatusLabels.DRAFT!,
      cssClass: labReportStatusClasses.DRAFT!,
    };
  }

  const allVerified = results.every((r) => r.verification_status === 'VERIFIED');
  return allVerified
    ? { label: labReportStatusLabels.FINAL!, cssClass: labReportStatusClasses.FINAL! }
    : {
        label: labReportStatusLabels.PRELIMINARY!,
        cssClass: labReportStatusClasses.PRELIMINARY!,
      };
}

function buildResultsRows(order: LabOrder): { rowsHtml: string; hasCritical: boolean } {
  const items = getOrderItems(order);

  let hasCritical = false;
  const rowsHtml = items
    .map((item, index) => {
      const result = getResultForItem(item);

      const testName = escapeHtml(item.test_name || item.test_code || '');
      const value = result?.text_value || result?.option_value || result?.numeric_value;
      const valueStr = value === null || value === undefined ? '' : escapeHtml(String(value));

      const flag = result?.result_flag ? escapeHtml(String(result.result_flag)) : '';
      const verified = result?.verification_status === 'VERIFIED' ? 'Yes' : 'No';

      if (result?.is_critical_result) hasCritical = true;

      return `
        <tr>
          <td>${index + 1}</td>
          <td>${testName}</td>
          <td>${valueStr}</td>
          <td>${flag}</td>
          <td>${verified}</td>
        </tr>
      `.trim();
    })
    .join('\n');

  return { rowsHtml, hasCritical };
}

function buildTemplateData(data: PrintLabReportData): Record<string, unknown> {
  const { order } = data;
  const reportStatus = computeReportStatus(order);
  const { rowsHtml, hasCritical } = buildResultsRows(order);

  const patientName =
    data.patient?.full_name ||
    data.patient?.name ||
    order.patient_name ||
    '';

  const patientMrn = data.patient?.mrn || order.patient_mrn || '';

  const orderedAt = order.ordered_at ? formatDateTime(order.ordered_at) : '';
  const reportDate = order.completed_at || order.ordered_at;

  const notes = order.clinical_notes || '';

  return {
    facility: {
      ...labReportDefaults.facility,
      ...data.facility,
    },
    order: {
      number: escapeHtml(order.order_number),
      priority: escapeHtml(order.priority),
      ordered_at: escapeHtml(orderedAt),
      ordered_by: escapeHtml(order.ordered_by_name || ''),
      notes: escapeHtml(notes),
    },
    report: {
      date: escapeHtml(reportDate ? formatDate(reportDate) : ''),
      status_label: reportStatus.label,
      status_class: reportStatus.cssClass,
    },
    patient: {
      name: escapeHtml(patientName),
      mrn: escapeHtml(patientMrn),
      age: escapeHtml(String(data.patient?.age ?? '')),
      sex: escapeHtml(String(data.patient?.sex ?? '')),
    },
    critical: {
      display: hasCritical ? '' : 'display:none;',
    },
    notes: {
      display: notes ? '' : 'display:none;',
    },
    results: {
      rows: rowsHtml,
    },
    signature: {
      name: '',
      credentials: labReportDefaults.signature_credentials,
      datetime: '',
      status: reportStatus.label === 'Final' ? 'Electronically verified' : 'Not fully verified',
    },
    system: {
      name: labReportDefaults.system_name,
    },
  };
}

function getLabReportQRContent(data: PrintLabReportData): QRContent {
  return getLabResultQRContent({
    order_number: data.order.order_number,
    verification_url: data.verificationUrl,
  });
}

// =============================================================================
// PRINT
// =============================================================================

export async function printLabReport(data: PrintLabReportData): Promise<void> {
  const templateData = buildTemplateData(data);

  const qrContent = getLabReportQRContent(data);
  const qrDataUri = await generateQRDataUri(qrContent.data, { size: 60 });

  let html = replaceTemplatePlaceholders(LAB_REPORT_TEMPLATE, templateData);
  html = html.replace(/>QR<\/div>/g, `><img src="${qrDataUri}" alt="QR Code" /></div>`);

  const title = `Laboratory Report - ${data.order.order_number}`;
  const fullHtml = buildPrintDocument(html, title, data.layout || 'a4', data.theme || 'default', LAB_REPORT_CSS);

  openPrintWindow(fullHtml);
}

export default printLabReport;
