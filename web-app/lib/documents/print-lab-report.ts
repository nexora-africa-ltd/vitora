// Use Omit to allow full_name to be optional (PatientInfo requires it)
interface LabReportPatientInfo extends Omit<PatientInfo, 'full_name'> {
  name?: string; // allow alternate naming for convenience
  full_name?: string;
  mrn?: string;
  age?: string | number;
  sex?: string;
}

export interface PrintLabReportData {
  order: LabOrder;
  patient?: LabReportPatientInfo;
  facility?: Partial<FacilityInfo>;
  layout?: LayoutType;
  theme?: string;
  verificationUrl?: string;
}

